tmp = Path(__file__).resolve().parent
destination = tmp.parent / 'report-v1.json'
authority_path = tmp.parent / 'authority-v1.json'
authority = json.loads(authority_path.read_text())
assert not any(Path(p).exists() for p in authority['stop_authority']['paths'])
root = Path(authority['worktree'])
before = authority['source']
run_path = tmp / 'run-committed-1.json'
run = json.loads(run_path.read_text())
def git(*args):
    return subprocess.check_output(['git', *args], cwd=root, text=True).strip()
def ref(path):
    path = Path(path)
    raw = path.read_bytes()
    return dict(path=str(path), sha256=hashlib.sha256(raw).hexdigest(), bytes=len(raw))
after = git('rev-parse', 'HEAD')
changed = git('diff', '--name-only', before, after).splitlines()
assert changed == ['tests/test_n36_readiness_prepare.py']
assert run['source_commit'] == run['source_after'] == after
assert run['exit_code'] == 0 and run['source_hashes_unchanged']
