"""Administrative two-file source bridge. No new arithmetic proof or data reads."""
import ast
import hashlib
import subprocess
from pathlib import Path
from scripts import qd_ed_n23_worker as w
from scripts import qd_ed_n25_cont_evidence as e

ROUTES={'scripts/qd_ed_final_runner.py':{'metered_support','check_budget','check_retry'},
 'scripts/qd_ed_n23_worker.py':{'validate_context'}}
DOC='experiments/qd_ed_n25_continuation'
MODULES={'scripts/qd_ed_n25_cont_'+n+'.py' for n in ('evidence','seal','bridge','contract','prepare','supervise','report','terminal')}
EXTRAS=MODULES|{DOC+'/'+n for n in ('protocol-v1.md','original-source-v1.json','reverse-routes-v1.json','controller-contract-v1.md')}
EXTRAS|={'tests/test_qd_ed_n25_cont.py','tests/n25_cont_fixtures.py'}

def functions(text):return {n.name:ast.get_source_segment(text,n) for n in ast.parse(text).body if isinstance(n,ast.FunctionDef)}

def source_paths(root):
    old=w.read_ref(e.ref(Path(root)/DOC/'original-source-v1.json'))
    return {r['path'] for r in old['files']}|EXTRAS

def build(source,seal,root):
    root=Path(root);old=w.read_ref(e.ref(root/DOC/'original-source-v1.json'))
    w.require(old==seal['original_source'] and old['commit']==e.BASE and len(old['files'])==257,'original257 bridge differs')
    w.require({r['path'] for r in source['files']}==source_paths(root),'complete continuation source closure')
    reverse=w.read_ref(e.ref(root/DOC/'reverse-routes-v1.json'));deltas=[];same=[]
    w.require(reverse['base_commit']==e.BASE and {r['path'] for r in reverse['files']}==set(ROUTES),'reverse route scope')
    for row in old['files']:
        p=row['path'];b=(root/p).read_bytes()
        if p not in ROUTES:
            w.require(hashlib.sha256(b).hexdigest()==row['sha256'],'original scientific/source bytes changed: '+p);same.append(row);continue
        record=next(x for x in reverse['files'] if x['path']==p);lines=b.decode().splitlines(keepends=True)
        w.require(record['new_sha256']==hashlib.sha256(b).hexdigest() and record['old_sha256']==row['sha256'],'shared route bytes differ')
        for edit in reversed(record['edits']):
            a,z=edit['new_start'],edit['new_end'];w.require(''.join(lines[a:z])==edit['new'],'reverse edit differs');lines[a:z]=edit['old'].splitlines(keepends=True)
        oldb=''.join(lines).encode();w.require(hashlib.sha256(oldb).hexdigest()==row['sha256'],'whole-file reverse differs')
        a,z=functions(oldb.decode()),functions(b.decode())
        w.require(set(a)==set(z) and {k for k in a if a[k]!=z[k]}==ROUTES[p],'unlisted shared function changed')
        deltas.append({'path':p,'original_sha256':row['sha256'],'new_sha256':record['new_sha256'],'functions':sorted(ROUTES[p]),'reverse_exact':True})
    changed=set(subprocess.check_output(['git','diff','--name-only',e.BASE,source['commit']],cwd=root,text=True).splitlines())
    w.require(changed<=EXTRAS|set(ROUTES),'unlisted source delta')
    return {'schema':'n25-continuation-source-bridge-v1','old_source':old,'new_source':source,'same_files':same,
        'shared_routes':deltas,'historical_backend_proof':seal['historical_backend_proof'],'new_numerical_preflight':False,
        'interpretation':'Historical5a proof is not generated by new commit; unchanged science/native arithmetic plus reviewed administrative route bridge.'}
